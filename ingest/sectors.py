def classify_sector(code: str, name: str) -> str:
    """종목코드 또는 종목명으로 섹터 결정. 매칭 실패 시 '기타'."""
    if code in TICKER_TO_SECTOR:
        return TICKER_TO_SECTOR[code]
    for keywords, sector in KEYWORD_RULES:
        if any(kw in name for kw in keywords):
            return sector
    return "기타"
